type Category = (typeof categories)[number];

export type StoreProduct = Product & {
  category: Category;
  description: string;
  rating: number;
  featured: boolean;
};

function sample(
  category: Category,
  id: string,
  name: string,
  price: number,
  discountPercent: number,
  rating: number,
  description: string,
  featured = false,
): StoreProduct {
  return {
    id,
    groupId: category.id,
    groupName: category.name,
    groupCode: category.code,
    code: `SAMPLE-${category.code}`,
    name,
    unit: category.id === "fabrics" || category.id === "laces" ? "MT" : "NO",
    price,
    discountPercent,
    category,
    description,
    rating,
    featured,
  };
}

